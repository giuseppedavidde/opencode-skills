def install_workspace(options: Options) -> None:
    """Install the VS Code layer into a workspace folder."""
    if options.workspace is None:
        raise SystemExit("--workspace is required for the workspace target")
    workspace = options.workspace.expanduser().resolve()
    if not workspace.is_dir():
        raise SystemExit(f"workspace does not exist: {workspace}")

    print(f"\nWorkspace target: {workspace}")
    github = workspace / ".github"
    install_skills(github / "skills", options)
    install_command_skills(github / "skills", options)
    install_agents(github / "agents", ".github/skills", options)
    remove_generated_prompts(github / "prompts", options)

    replacements = workspace_replacements(workspace, options)
    install_instructions(github / "copilot-instructions.md", replacements, options)
    install_python_instructions(
        github / "instructions" / "python.instructions.md", replacements, options
    )

    install_mcp_workspace(workspace, options)
    install_hooks(github / "hooks", workspace, options)

    # These settings control only the deprecated Local harness.
    settings_updates: dict[str, object] = {
        "chat.useAgentSkills": True,
        "chat.useHooks": True,
    }
    default_model = default_model_id()
    if default_model:
        settings_updates["chat.defaultModel"] = default_model

    merge_json(
        workspace / ".vscode" / "settings.json",
        settings_updates,
        options,
        "settings",
    )

    for stray in stray_duplicates(workspace):
        print(
            f"NOTE: {stray} is a nested copy that VS Code never reads "
            "(only <workspaceRoot>/.github is scanned). Delete it to avoid confusion."
        )

    if user_layer_present():
        options.warn(
            "the user layer (~/.copilot) also contains the opencode-skills agents; "
            "keep one scope, or every agent, skill and hook loads two times"
        )


def user_layer_present() -> bool:
    """True when ~/.copilot holds agents that this installer generated."""
    agents = Path.home() / ".copilot" / "agents"
    return any(
        (agents / f"{name}.agent.md").is_file() and is_managed_file(agents / f"{name}.agent.md")
        for name in agent_names()
    )


def legacy_workspace_links() -> list[Path]:
    """Return workspace `.github` entries that link into ~/.copilot (old per-item layout).

    Such a link makes the Copilot harness load the user layer a second time.
    The folders that contain the repository are the usual workspace roots.
    """
    copilot = (Path.home() / ".copilot").resolve()
    found: list[Path] = []
    for root in {REPO_ROOT.parent, REPO_ROOT.parent.parent}:
        github = root / ".github"
        entries = [github] if github.is_symlink() else [
            github / name for name in ("agents", "skills", "hooks", "instructions", "copilot-instructions.md")
        ]
        for entry in entries:
            try:
                if entry.is_symlink() and (entry.resolve() == copilot or copilot in entry.resolve().parents):
                    found.append(entry)
            except OSError:
                continue
    return sorted(found)


def install_user(options: Options) -> None:
    """Install the VS Code layer at user scope (~/.copilot)."""
    home = Path.home()
    copilot = home / ".copilot"

    print(f"\nUser target: {copilot}")
    install_skills(copilot / "skills", options)
    install_command_skills(copilot / "skills", options)
    install_agents(copilot / "agents", "~/.copilot/skills", options)
    for folder in user_prompt_folders():
        remove_generated_prompts(folder, options)

    replacements = user_replacements()
    install_instructions(copilot / "copilot-instructions.md", replacements, options)
    install_python_instructions(
        copilot / "instructions" / "python.instructions.md", replacements, options
    )

    if not options.no_mcp:
        install_mcp(copilot / "mcp-config.json", "mcpServers", options)
    install_hooks(copilot / "hooks", Path.home(), options)

    for link in legacy_workspace_links():
        options.warn(
            f"{link} links into ~/.copilot (old per-item layout): the user layer loads two "
            f"times; remove the link with: rm {link}"
        )


