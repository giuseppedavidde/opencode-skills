def install_mcp(path: Path, key: str, options: Options) -> None:
    """Write or merge MCP server definitions.

    The servers of config/opencode.json are managed entries and follow that
    file and this machine: a disabled server, or a server without its runtime,
    is removed. Other servers in the target file stay unchanged.
    """
    plan = mcp_plan()
    for name, reason in sorted(plan.disabled.items()):
        options.log(f"SKIP mcp {name}: {reason}")
    for name, reason in sorted(plan.missing.items()):
        options.warn(f"mcp {name}: left out, {reason}")
    for warning in plan.warnings:
        options.warn(warning)

    existing: dict = {}
    if path.is_file():
        try:
            existing = load_json_file(path)
        except Exception as exc:
            options.warn(f"mcp: cannot parse {path} ({exc}); not overwritten")
            return
    current = existing.get(key)
    if not isinstance(current, dict):
        current = {}
    stale = sorted(name for name in plan.left_out() if name in current)
    if not plan.servers and not stale:
        options.log("SKIP mcp: no server is ready (see config/opencode.json and the warnings)")
        return
    for name in stale:
        del current[name]
        options.log(f"REMOVE mcp server {name} from {path} ({plan.left_out()[name]})")
    current.update(plan.servers)
    existing[key] = current
    write_json(path, existing, options, "mcp", owned=True)


HOOK_SCRIPTS = ("verifica_gate.py", "graphify_reminder.py")

# Text that files of older installer versions contain (they have no marker).
LEGACY_SIGNATURES = (
    "opencode `## VERIFICA` contract",
    "remind the model to query an existing graphify graph",
    "# opencode-skills workflow in VS Code",
    "Python standards from the opencode-skills workflow",
)


def owned_or_legacy(path: Path) -> bool:
    """True when the installer generated `path`, now or in an older version."""
    if is_managed_file(path):
        return True
    try:
        head = path.read_text(encoding="utf-8", errors="replace")[:4096]
    except OSError:
        return False
    return any(signature in head for signature in LEGACY_SIGNATURES)


def owned_for_update(path: Path, content: str, options: Options) -> bool:
    """Return True when the installer may update `path`; back up a legacy file first.

    A file of an older installer version has no marker, and the user can have
    edited it, so it goes to the backup folder before the update.
    """
    if not path.exists() or is_managed_file(path):
        return True
    if not owned_or_legacy(path):
        return False
    try:
        if path.read_text(encoding="utf-8") == content:
            return True
    except OSError:
        pass
    options.backup(path)
    return True


def hook_python() -> str:
    """Return a python3 path for hook commands that does not depend on the PATH order."""
    for candidate in ("/usr/bin/python3", "/usr/local/bin/python3"):
        if os.access(candidate, os.X_OK):
            return candidate
    return shutil.which("python3") or sys.executable or "python3"


def hook_configs(hooks_root: Path, cwd: Path) -> dict[str, dict]:
    """Return {file name: hook configuration} for one hooks folder.

    The files use the Copilot hook format (`version: 1`). The PascalCase event
    names select the VS Code-compatible payload (`last_assistant_message`).
    """
    python = hook_python()
    agents = ",".join(subagent_names())
    gate = f'{python} "{hooks_root / "verifica_gate.py"}" --agents={agents}'
    graphify = f'{python} "{hooks_root / "graphify_reminder.py"}"'
    return {
        "verifica-gate.json": {
            "version": 1,
            "hooks": {"SubagentStop": [{"type": "command", "command": gate, "cwd": str(cwd), "timeout": 15}]},
        },
        "graphify-reminder.json": {
            "version": 1,
            "hooks": {"SessionStart": [{"type": "command", "command": graphify, "cwd": str(cwd), "timeout": 10}]},
        },
    }


def hook_config_owned(path: Path) -> bool:
    """True when a hook configuration file runs one of the installer scripts."""
    try:
        text = path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return False
    return any(script in text for script in HOOK_SCRIPTS)


def install_hooks(hooks_root: Path, cwd: Path, options: Options) -> None:
    """Copy hook scripts and write hook configuration with absolute paths."""
    if options.no_hooks:
        options.log("SKIP hooks: disabled by --no-hooks")
        return

    for filename in HOOK_SCRIPTS:
        source = VSCODE_SRC / "hooks" / filename
        if not source.is_file():
            options.warn(f"hook script missing: {source}")
            continue
        destination = hooks_root / filename
        if destination.exists() and source.resolve() == destination.resolve():
            options.log(f"OK   hook script: {destination} (source)")
            continue
        content = source.read_text(encoding="utf-8")
        owned = owned_for_update(destination, content, options)
        written = write_text(destination, content, options, "hook script", owned)
        if written and not options.dry_run:
            destination.chmod(0o755)

    for filename, data in hook_configs(hooks_root, cwd).items():
        path = hooks_root / filename
        owned = hook_config_owned(path) if path.exists() else True
        write_json(path, data, options, "hook config", owned=owned)


