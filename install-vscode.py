#!/usr/bin/env python3
"""Install the opencode-skills workflow into VS Code (Copilot harness).

The opencode definitions in `skills/`, `agents/`, `command/`, and
`config/opencode.json` remain the single source of truth. This script generates
the VS Code-native equivalents:

    opencode                          VS Code
    ────────────────────────────────  ──────────────────────────────────────────
    skills/<name>/SKILL.md            <skills>/<name>/SKILL.md   (symlink)
    agents/<name>.md                  <agents>/<name>.agent.md   (generated)
    command/<name>.md                 <skills>/<name>/SKILL.md   (generated, slash-only)
    config/AGENTS.md                  copilot-instructions.md    (generated)
    config/opencode.json → mcp        ~/.copilot/mcp-config.json or .mcp.json
    plugins/verifica-gate             <hooks>/verifica-gate.json (SubagentStop)
    plugins/graphify                  <hooks>/graphify-reminder.json (SessionStart)

Usage:
    python3 install-vscode.py --target user            # recommended: all workspaces
    python3 install-vscode.py --workspace /path/to/workspace
    python3 install-vscode.py --verify --target user

Use one scope only. Each scope is a native Copilot source, so a second copy
loads every agent, skill, hook, and instruction file two times.

User target writes to `~/.copilot/` (skills, agents, hooks, instructions,
copilot-instructions.md, mcp-config.json). Workspace target writes `.github/`,
`.mcp.json` and `.vscode/settings.json` inside the workspace.

Files that this script did not generate are never overwritten without
`--force`. With `--force`, the old file goes to a backup folder first.
"""

