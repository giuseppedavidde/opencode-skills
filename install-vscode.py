def build_agent(
    source: Path,
    name: str,
    skills_dir: str,
    available: list[str],
    expose_subagents: bool = True,
) -> str | None:
    """Convert one opencode agent file to VS Code `.agent.md` content."""
    try:
        text = source.read_text(encoding="utf-8")
    except OSError:
        return None

    scalars, permission, body = parse_frontmatter(text)
    description = strip_quotes(scalars.get("description", ""))
    if not description:
        return None

    # Align opencode agent references with the generated VS Code agent names.
    for old, new in (
        ("coder_planner", "coder-planner"),
        ("graphify_helper", "graphify-helper"),
        ("pdf_reader", "pdf-reader"),
        ("skill_updater", "skill-updater"),
        ("oegk_health", "oegk-health"),
        ("vscode_ext_planner", "vscode-ext-planner"),
        ("vscode_ext", "vscode-ext"),
    ):
        description = description.replace(old, new)
        body = body.replace(old, new)

    # The book-to-skill agent writes generated skills. Point it at the root
    # that this VS Code target reads instead of the opencode root.
    if name == "book-to-skill-agent":
        skill_root = skills_dir
        if skill_root.startswith("~/"):
            skill_root = "$HOME/" + skill_root[2:]
        for opencode_root in (
            "${HOME}/.config/opencode/skills",
            "$HOME/.config/opencode/skills",
            "~/.config/opencode/skills",
        ):
            body = body.replace(opencode_root, skill_root)

    if name == "router":
        body = body.replace("on the opencode CLI", "in VS Code Copilot Chat")
    for opencode_name, copilot_name in BUILTIN_AGENT_NAMES.items():
        body = body.replace(f'subagent_type="{opencode_name}"', f'subagent_type="{copilot_name}"')

    mode = strip_quotes(scalars.get("mode", "subagent"))
    models = models_for(scalars.get("model", ""))
    reasoning_effort = reasoning_effort_for(name, scalars.get("model", ""))
    tools = tools_for(permission, name)

    lines = ["---", f"description: {json.dumps(description, ensure_ascii=False)}"]
    if models:
        lines.append(f"model: {json.dumps(models, ensure_ascii=False)}")
    lines.append(f"reasoning-effort: {reasoning_effort}")
    lines.append(f"tools: {json.dumps(tools, ensure_ascii=False)}")
    invocable = mode == "primary" or expose_subagents
    lines.append(f"user-invocable: {'true' if invocable else 'false'}")
    if mode != "primary":
        lines.append("disable-model-invocation: false")
    if name == "router":
        subagents = [item for item in available if item != name]
        lines.append(f"agents: {json.dumps(subagents, ensure_ascii=False)}")
        hint = "Describe the task; the router delegates to " + ", ".join(subagents) + "."
        lines.append(f"argument-hint: {json.dumps(hint, ensure_ascii=False)}")
    lines.append("---")
    lines.append("")

    preamble = agent_preamble(name, source.stem, skills_dir, available)
    return "\n".join(lines) + preamble + body.lstrip("\n")


