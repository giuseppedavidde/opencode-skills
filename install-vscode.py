def resolve_env_placeholders(value: str) -> str:
    """Replace opencode `{env:NAME}` placeholders with the value of NAME (empty when unset)."""
    return ENV_PLACEHOLDER_RE.sub(lambda match: os.environ.get(match.group(1), ""), value)


def opencode_mcp_entries(config: dict) -> list[tuple[str, object]]:
    """Return (name, spec) for every MCP server: V2 `mcp.servers` first, then the deprecated V1 form."""
    mcp = config.get("mcp")
    if not isinstance(mcp, dict):
        return []
    entries: list[tuple[str, object]] = []
    servers = mcp.get("servers")
    if isinstance(servers, dict):
        entries.extend(servers.items())
    entries.extend((name, spec) for name, spec in mcp.items() if name not in ("servers", "timeout"))
    return entries


def mcp_servers_from_opencode(skipped: dict[str, str] | None = None) -> dict[str, dict]:
    """Convert the opencode MCP config to portable Copilot server definitions.

    Reads OpenCode V2 entries (`mcp.servers.<name>`) and deprecated V1 entries
    (`mcp.<name>`). `{env:NAME}` placeholders resolve on this machine. A
    disabled server, or an entry without a command, goes to `skipped`
    (name → reason).
    """
    skipped = skipped if skipped is not None else {}
    config = opencode_config()
    servers: dict[str, dict] = {}
    for name, spec in opencode_mcp_entries(config):
        if name in servers or name in skipped:
            continue
        if not isinstance(spec, dict):
            skipped[name] = "not a server object in config/opencode.json"
            continue
        if spec.get("disabled") is True or spec.get("enabled") is False:
            skipped[name] = "disabled in config/opencode.json"
            continue
        if spec.get("type") == "remote":
            url = spec.get("url")
            if not isinstance(url, str) or not url:
                skipped[name] = "remote server without url in config/opencode.json"
                continue
            server: dict = {"type": "http", "url": resolve_env_placeholders(url)}
            headers = spec.get("headers")
            if isinstance(headers, dict) and headers:
                server["headers"] = {str(k): resolve_env_placeholders(str(v)) for k, v in headers.items()}
            servers[name] = server
            continue
        command = spec.get("command")
        if isinstance(command, list) and command:
            executable, args = str(command[0]), [str(item) for item in command[1:]]
        elif isinstance(command, str) and command:
            executable, args = command, []
        else:
            skipped[name] = "no command in config/opencode.json"
            continue
        server = {
            "type": "stdio",
            "command": resolve_env_placeholders(executable),
            "args": [resolve_env_placeholders(item) for item in args],
        }
        environment = spec.get("environment")
        if isinstance(environment, dict) and environment:
            server["env"] = {str(key): resolve_env_placeholders(str(value)) for key, value in environment.items()}
        cwd = spec.get("cwd")
        if isinstance(cwd, str) and cwd:
            server["cwd"] = str(Path(resolve_env_placeholders(cwd)).expanduser())
        servers[name] = server
    return servers


MCP_SETUP_HINTS = {
    "headroom": "run ./setup-headroom.sh, then rerun ./install.sh",
    "trading": "run ./setup-trading-mcp.sh, then rerun ./install.sh",
    "rea": "run ./install.sh --with-rea",
    "browse": "install browse (curl -fsSL https://opencode.ai/browse/install | bash), then rerun ./install.sh",
}
DEFAULT_SETUP_HINT = "install its runtime, then rerun ./install.sh"
EXEC_TARGET_RE = re.compile(r'exec\s+"([^"]+)"|exec\s+([^\s;]+)')
# Prints the code folder of the venv, then starts the server: a missing package fails at import time.
TRADING_START_PROBE = (
    "import importlib.util, os\n"
    "spec = importlib.util.find_spec('trading_mcp')\n"
    "print(os.path.realpath(os.path.dirname(spec.origin)) if spec and spec.origin else '', flush=True)\n"
    "from trading_mcp.mcp import initialize_mcp\n"
    "initialize_mcp()\n"
)


@dataclass
class McpPlan:
    """The managed MCP servers, split by what the installer does with them."""

    servers: dict[str, dict] = field(default_factory=dict)
    disabled: dict[str, str] = field(default_factory=dict)
    missing: dict[str, str] = field(default_factory=dict)
    warnings: list[str] = field(default_factory=list)

    def left_out(self) -> dict[str, str]:
        """Return the managed servers that the target file must not contain (name → reason)."""
        return {**self.disabled, **self.missing}


def server_runtime_path(server: dict) -> Path | None:
    """Return the executable that a server starts, when it can be found statically."""
    command = str(server.get("command", ""))
    args = [str(item) for item in server.get("args") or []]
    if Path(command).name in ("bash", "sh", "zsh") and len(args) >= 2 and args[0] == "-c":
        match = EXEC_TARGET_RE.search(args[1])
        if not match:
            return None
        return Path(os.path.expandvars(match.group(1) or match.group(2))).expanduser()
    if os.path.isabs(command):
        return Path(command)
    return None


def rea_checkout() -> Path:
    """Return the rea checkout that config/bin/rea-mcp.sh serves (the same rules as the script)."""
    configured = os.environ.get("REA_REPO")
    if configured:
        return Path(configured).expanduser()
    anchor = Path.home() / ".config" / "opencode" / "opencode-skills"
    if anchor.exists():
        return anchor.resolve().parent / "rea"
    return Path.home() / ".local" / "share" / "opencode" / "rea"


def runtime_requirements(name: str, server: dict) -> list[Path]:
    """Return the paths that a server must find on this machine to start."""
    paths: list[Path] = []
    executable = server_runtime_path(server)
    if executable is not None:
        paths.append(executable)
    if name == "rea":
        paths.append(rea_checkout())
    return paths


def trading_runtime_check(executable: Path) -> tuple[str | None, str | None]:
    """Start the trading server once with its venv python.

    Returns (error, warning): `error` when the server cannot start, `warning`
    when the venv runs the code of a different clone. A runtime without a
    python next to it (a custom install) is not checked.
    """
    python = executable.parent / "python"
    if not python.exists():
        return None, None
    try:
        result = subprocess.run(
            [str(python), "-c", TRADING_START_PROBE],
            capture_output=True,
            text=True,
            timeout=180,
            check=False,
            cwd=tempfile.gettempdir(),
        )
    except (OSError, subprocess.SubprocessError) as exc:
        return f"start check failed ({exc.__class__.__name__})", None
    lines = result.stdout.strip().splitlines()
    current = lines[0].strip() if lines else ""
    expected = (REPO_ROOT / "mcp" / "src" / "trading_mcp").resolve()
    warning = None
    if current and Path(current) != expected:
        warning = f"mcp trading: the venv runs the code in {current}, not this clone; run ./setup-trading-mcp.sh"
    if result.returncode != 0:
        detail = (result.stderr.strip().splitlines() or ["unknown error"])[-1]
        return f"the server does not start ({detail})", warning
    return None, warning


def mcp_plan() -> McpPlan:
    """Decide which managed MCP servers the VS Code layer gets on this machine.

    A server whose runtime is absent is left out, because the harness shows
    an error for each server that cannot start. Its setup hint tells the user
    what to run.
    """
    plan = McpPlan()
    for name, server in mcp_servers_from_opencode(plan.disabled).items():
        absent = next((path for path in runtime_requirements(name, server) if not path.exists()), None)
        if absent is not None:
            plan.missing[name] = f"{absent} not found; {MCP_SETUP_HINTS.get(name, DEFAULT_SETUP_HINT)}"
            continue
        executable = server_runtime_path(server)
        if name == "trading" and executable is not None:
            error, warning = trading_runtime_check(executable)
            if warning:
                plan.warnings.append(warning)
            if error:
                plan.missing[name] = f"{error}; {MCP_SETUP_HINTS['trading']}"
                continue
        plan.servers[name] = server
    return plan


