def run_verify(options: Options) -> int:
    """Run the compatibility check and return a process exit code."""
    print("opencode-skills → VS Code compatibility check")
    print(f"Source: {REPO_ROOT}")
    print(f"Target: {options.target}")

    source_warnings = validate_skills()
    problems: list[str] = []
    notes: list[str] = []

    if options.target in ("workspace", "both"):
        found, found_notes = verify_workspace(options)
        problems += found
        notes += found_notes
    if options.target in ("user", "both"):
        found, found_notes = verify_user(options)
        problems += found
        notes += found_notes

    runtime_evidence(notes)

    print("\nChecks:")
    for note in notes:
        print(f"  · {note}")

    if source_warnings:
        print("\nSource warnings:")
        for warning in source_warnings:
            print(f"  ! {warning}")

    if problems:
        print(f"\nDRIFT / MISSING ({len(problems)}):")
        for problem in problems:
            print(f"  x {problem}")
        print("\nVerdict: the VS Code layer is NOT in sync with opencode-skills.")
        if options.target == "user":
            print("Fix: python3 install-vscode.py --target user")
        elif options.workspace is not None:
            print(f"Fix: python3 install-vscode.py --workspace {options.workspace}")
        else:
            print("Fix: python3 install-vscode.py --workspace <workspace>")
        print("     (add --force only to replace files that the installer did not generate)")
        return 1

    print("\nVerdict: the VS Code layer matches opencode-skills (no drift).")
    print("In-chat proof: start a NEW chat session, type '/' to list the skills,")
    ready = sorted(mcp_plan().servers) if not options.no_mcp else []
    if ready:
        print(f"open the agent picker, and check the MCP view for {' / '.join(ready)}.")
    else:
        print("and open the agent picker.")
    return 0


def parse_args(argv: list[str] | None = None) -> Options:
    """Parse command-line arguments."""
    parser = argparse.ArgumentParser(
        description="Install the opencode-skills workflow into VS Code (Copilot harness).",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=__doc__,
    )
    parser.add_argument(
        "--target",
        choices=("workspace", "user", "both"),
        default=None,
        help="Where to install (default: workspace when --workspace is given, else user)",
    )
    parser.add_argument(
        "--workspace",
        type=Path,
        default=os.environ.get("VSCODE_WORKSPACE"),
        help="Workspace folder for the workspace target (default: $VSCODE_WORKSPACE)",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="Replace files and links that the installer did not generate (old copies go to a backup folder)",
    )
    parser.add_argument("--dry-run", action="store_true", help="Print actions without writing")
    parser.add_argument("--no-hooks", action="store_true", help="Skip VS Code hook generation")
    parser.add_argument("--no-mcp", action="store_true", help="Skip MCP server generation")
    parser.add_argument("-v", "--verbose", action="store_true", help="Print every action")
    parser.add_argument(
        "--mcp-format",
        choices=("vscode", "portable", "both"),
        default="portable",
        help=(
            "Workspace MCP file: 'portable' = .mcp.json, read by the Copilot harness "
            "(default); 'vscode' = .vscode/mcp.json (deprecated Local format); 'both'"
        ),
    )
    parser.add_argument(
        "--expose-subagents",
        action=argparse.BooleanOptionalAction,
        default=True,
        help=(
            "Show subagents (trade, coder, ...) in the agent picker as well "
            "(default: on; use --no-expose-subagents for a router-only picker)"
        ),
    )
    parser.add_argument(
        "--verify",
        action="store_true",
        help="Only check that the installed VS Code layer matches the opencode sources",
    )
    args = parser.parse_args(argv)
    target = args.target or ("workspace" if args.workspace else "user")

    return Options(
        target=target,
        workspace=Path(args.workspace) if args.workspace else None,
        force=args.force,
        dry_run=args.dry_run,
        no_hooks=args.no_hooks,
        no_mcp=args.no_mcp,
        verbose=args.verbose,
        verify=args.verify,
        expose_subagents=args.expose_subagents,
        mcp_format=args.mcp_format,
    )


def main(argv: list[str] | None = None) -> int:
    """Run the installer."""
    options = parse_args(argv)

    if options.verify:
        return run_verify(options)

    print("opencode-skills → VS Code compatibility installer")
    print(f"Source: {REPO_ROOT}")
    print(f"Target: {options.target}{' (dry run)' if options.dry_run else ''}")

    problems = validate_skills()
    if problems:
        print("\nSkill validation warnings:")
        for problem in problems:
            print(f"  - {problem}")
    else:
        print(f"\nSkill validation: OK ({len(skill_directories())} skills)")

    if options.target in ("workspace", "both"):
        install_workspace(options)
    if options.target in ("user", "both"):
        install_user(options)
    if options.target == "both":
        options.warn(
            "both scopes installed: every agent, skill and hook loads two times; prefer one scope"
        )

    if options.warnings:
        print(f"\nWarnings ({len(options.warnings)}):")
        for warning in options.warnings:
            print(f"  ! {warning}")
    if options.backup_root is not None:
        print(f"\nBackups of replaced files: {options.backup_root}")
    print(f"\nDone: {len(options.actions)} actions.")
    print("Start a NEW chat session in VS Code: the runtime reads agents and skills at session start.")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except KeyboardInterrupt:
        sys.exit(130)
