@dataclass
class Options:
    """Installer options."""

    target: str = "workspace"
    workspace: Path | None = None
    force: bool = False
    dry_run: bool = False
    no_hooks: bool = False
    no_mcp: bool = False
    verbose: bool = False
    verify: bool = False
    expose_subagents: bool = True
    mcp_format: str = "portable"
    actions: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)
    backup_root: Path | None = None

    def log(self, message: str) -> None:
        """Record an action and print it when verbose."""
        self.actions.append(message)
        if self.verbose:
            print(message)

    def warn(self, message: str) -> None:
        """Record a warning; warnings are always printed in the summary."""
        if message not in self.warnings:
            self.warnings.append(message)
        self.log(f"WARN {message}")

    def backup(self, path: Path) -> Path | None:
        """Move `path` into the backup folder and return the new location."""
        if self.dry_run:
            self.log(f"DRY  backup: would move {path}")
            return None
        if self.backup_root is None:
            cache = Path(os.environ.get("XDG_CACHE_HOME", str(Path.home() / ".cache")))
            self.backup_root = cache / "opencode-skills" / "backup" / time.strftime("%Y%m%d-%H%M%S")
        relative = Path(*path.expanduser().absolute().parts[1:])
        destination = self.backup_root / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.move(str(path), str(destination))
        self.log(f"BACKUP {path} -> {destination}")
        return destination


def strip_quotes(value: str) -> str:
    """Remove matching single or double quotes."""
    value = value.strip()
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
        return value[1:-1]
    return value


def parse_frontmatter(text: str) -> tuple[dict[str, str], dict[str, str], str]:
    """Return (top-level scalars, permission keys, body).

    This intentionally implements only the small YAML subset used by the
    opencode agent/command files, so the installer has no PyYAML dependency.
    """
    match = FRONTMATTER_RE.match(text)
    if not match:
        return {}, {}, text

    raw, body = match.group(1), match.group(2)
    scalars: dict[str, str] = {}
    permission: dict[str, str] = {}
    lines = raw.splitlines()
    in_permission = False
    index = 0

    while index < len(lines):
        line = lines[index]
        if not line.strip():
            index += 1
            continue

        if re.match(r"^permission:\s*$", line):
            in_permission = True
            index += 1
            continue

        if in_permission:
            if line.startswith("  ") and not line.startswith("    "):
                key, _, value = line.strip().partition(":")
                permission[key.strip()] = value.strip()
                index += 1
                continue
            if not line.startswith((" ", "\t")):
                in_permission = False
            else:
                index += 1
                continue

        if line.startswith((" ", "\t")):
            index += 1
            continue

        key, _, value = line.partition(":")
        key = key.strip()
        value = value.strip()

        # Folded/literal block scalar: join the indented lines into one value.
        if value in (">", "|", ">-", "|-", ">+", "|+"):
            index += 1
            block: list[str] = []
            while index < len(lines) and (lines[index].startswith("  ") or not lines[index].strip()):
                block.append(lines[index].strip())
                index += 1
            scalars[key] = " ".join(part for part in block if part).strip()
            continue

        scalars[key] = value
        index += 1

    return scalars, permission, body


def permission_allowed(permission: dict[str, str], key: str) -> bool:
    """True when a permission key is present and not explicitly denied."""
    if key not in permission:
        return False
    value = permission[key].strip()
    if value in ("deny", "false", "no"):
        return False
    return True


def tools_for(permission: dict[str, str], agent_name: str = "") -> list[str]:
    """Map opencode permissions to Copilot tool aliases and MCP tool names."""
    tools: list[str] = []

    def add(tool: str) -> None:
        if tool not in tools:
            tools.append(tool)

    if permission_allowed(permission, "read"):
        add("read")
    if permission_allowed(permission, "glob") or permission_allowed(permission, "grep"):
        add("search")
    # Path-scoped write maps (e.g. router) cannot be expressed in VS Code, so
    # only an explicit scalar `write: allow` / `edit: allow` grants edit.
    if permission.get("edit", "").strip() == "allow" or permission.get("write", "").strip() == "allow":
        add("edit")
        # The `edit` alias does not include these tools; GPT models edit with
        # apply_patch. The runtime ignores names that it does not know.
        add("create")
        add("apply_patch")
    if permission_allowed(permission, "bash"):
        add("execute")
    if permission_allowed(permission, "webfetch"):
        add("web")
    if permission_allowed(permission, "task"):
        add("agent")
    if permission_allowed(permission, "todowrite"):
        add("todo")
    if permission_allowed(permission, "trading_*"):
        add("trading/*")
    else:
        for tool in sorted(TRADING_TOOLS):
            if permission_allowed(permission, tool):
                add(f"trading/{tool}")
    if "headroom_*" in permission:
        add("headroom/*")
    # REA is the reverse-engineering MCP server used by the coder workflow.
    if agent_name == "coder":
        add("rea/*")

    if not tools:
        add("read")
        add("search")
    return tools


def load_model_map() -> dict:
    """Return vscode/models.json (empty when the file is absent or invalid)."""
    try:
        data = json.loads(MODELS_FILE.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}
    return data if isinstance(data, dict) else {}


def provider_prefix() -> str:
    """Return the VS Code vendor id of the OpenCode Go models (vscode/models.json)."""
    return str(load_model_map().get("provider_prefix") or "opencodego")


def model_for(raw_model: str) -> str | None:
    """Map an opencode model id to the VS Code id of the OpenCode Go provider.

    `opencode-go/deepseek-v4.1-flash#low` becomes
    `opencodego/deepseek-v4.1-flash`. A bare id without a provider is returned
    unchanged.
    """
    raw_model = strip_quotes(raw_model).split("#", 1)[0].strip()
    if not raw_model:
        return None
    vendor, sep, model = raw_model.rpartition("/")
    if sep and vendor in {"opencode-go", "opencodego"}:
        return f"{provider_prefix()}/{model}"
    return model


def fallback_model_id(entry: str) -> str:
    """Map a models.json fallback to a VS Code model id.

    A bare id is an OpenCode Go API id and gets the provider prefix. An entry
    with a slash or a qualifier, such as `GPT-6 Luna (copilot)`, stays unchanged.
    """
    entry = entry.strip()
    if not entry or "/" in entry or "(" in entry:
        return entry
    return f"{provider_prefix()}/{entry}"


def models_for(raw_model: str) -> list[str]:
    """Return the ordered model list: the model of the agent, then its fallbacks.

    The runtime uses the first available model. Without fallbacks, an agent
    whose provider is unavailable silently inherits the session model.
    """
    primary = model_for(raw_model)
    mapping = load_model_map()
    bare = strip_quotes(raw_model).split("#", 1)[0].strip().rpartition("/")[2]
    fallbacks = (mapping.get("fallbacks") or {}).get(bare) or mapping.get("default_fallback") or []
    models: list[str] = []
    for item in [primary, *(fallback_model_id(entry) for entry in fallbacks if isinstance(entry, str))]:
        if isinstance(item, str) and item and item not in models:
            models.append(item)
    return models


def reasoning_effort_for(name: str, raw_model: str) -> str:
    """Return the VS Code `reasoning-effort` level for one agent."""
    _, separator, suffix = strip_quotes(raw_model).partition("#")
    if separator and suffix.strip():
        return suffix.strip()
    return REASONING_EFFORT.get(name, DEFAULT_REASONING_EFFORT)


def skill_directories() -> list[Path]:
    """Return valid skill directories (must contain SKILL.md)."""
    if not SKILLS_SRC.is_dir():
        return []
    return sorted(
        path
        for path in SKILLS_SRC.iterdir()
        if path.is_dir() and not path.name.startswith(".") and (path / "SKILL.md").is_file()
    )


def validate_skills() -> list[str]:
    """Validate skill names/descriptions against VS Code discovery rules."""
    problems: list[str] = []
    for skill_dir in skill_directories():
        try:
            text = (skill_dir / "SKILL.md").read_text(encoding="utf-8", errors="replace")
        except OSError as exc:
            problems.append(f"{skill_dir.name}: cannot read SKILL.md ({exc})")
            continue
        scalars, _, _ = parse_frontmatter(text)
        name = strip_quotes(scalars.get("name", ""))
        description = strip_quotes(scalars.get("description", ""))
        if name != skill_dir.name:
            problems.append(f"{skill_dir.name}: frontmatter name is {name!r}")
        if not SKILL_NAME_RE.match(name):
            problems.append(f"{skill_dir.name}: name does not match [a-z0-9-]{{1,64}}")
        if not description:
            problems.append(f"{skill_dir.name}: missing description")
        elif len(description) > 1024:
            problems.append(f"{skill_dir.name}: description is {len(description)} chars (max 1024)")
    return problems


def ensure_parent(path: Path) -> None:
    """Create the parent directory of `path`."""
    path.parent.mkdir(parents=True, exist_ok=True)


def is_managed_file(path: Path) -> bool:
    """True when `path` carries an installer ownership marker."""
    try:
        head = path.read_text(encoding="utf-8", errors="replace")[:4096]
    except OSError:
        return False
    return GENERATED_MARKER in head or MANAGED_MARKER in head


def write_text(
    path: Path, content: str, options: Options, label: str, owned: bool | None = None
) -> bool:
    """Write a generated file, skipping identical content.

    An existing file that the installer does not own is kept unless `--force`
    is set; with `--force` it goes to the backup folder first. `owned`
    overrides the marker test for formats without comments (JSON).
    """
    if path.exists() and not path.is_file():
        options.warn(f"{label}: {path} exists and is not a file; skipped")
        return False
    if path.is_file():
        try:
            if path.read_text(encoding="utf-8") == content:
                options.log(f"OK   {label}: {path} (unchanged)")
                return True
        except OSError:
            pass
        mine = is_managed_file(path) if owned is None else owned
        if not mine:
            if not options.force:
                options.warn(f"{label}: {path} was not generated by this installer; kept (use --force)")
                return False
            options.backup(path)
    if options.dry_run:
        options.log(f"DRY  {label}: would write {path}")
        return True
    ensure_parent(path)
    path.write_text(content, encoding="utf-8")
    options.log(f"WROTE {label}: {path}")
    return True


def write_json(path: Path, data: dict, options: Options, label: str, owned: bool | None = None) -> bool:
    """Write JSON with stable formatting."""
    return write_text(path, json.dumps(data, indent=2, ensure_ascii=False) + "\n", options, label, owned)


def load_json_file(path: Path) -> dict:
    """Parse a JSON or JSONC file (VS Code settings/mcp allow comments); an empty file is `{}`."""
    text = path.read_text(encoding="utf-8")
    if not text.strip():
        return {}
    try:
        data = json.loads(text)
    except json.JSONDecodeError:
        data = json.loads(strip_jsonc(text))
    if not isinstance(data, dict):
        raise ValueError("top-level JSON value is not an object")
    return data


def strip_jsonc(text: str) -> str:
    """Remove // and /* */ comments plus trailing commas, preserving strings."""
    output: list[str] = []
    index = 0
    in_string = False
    escaped = False

    while index < len(text):
        char = text[index]
        if in_string:
            output.append(char)
            if escaped:
                escaped = False
            elif char == "\\":
                escaped = True
            elif char == '"':
                in_string = False
            index += 1
            continue

        if char == '"':
            in_string = True
            output.append(char)
            index += 1
            continue

        if char == "/" and index + 1 < len(text):
            next_char = text[index + 1]
            if next_char == "/":
                index += 2
                while index < len(text) and text[index] not in "\r\n":
                    index += 1
                continue
            if next_char == "*":
                index += 2
                while index + 1 < len(text) and not (text[index] == "*" and text[index + 1] == "/"):
                    index += 1
                index += 2
                continue

        output.append(char)
        index += 1

    return re.sub(r",(\s*[}\]])", r"\1", "".join(output))


def merge_json(path: Path, updates: dict, options: Options, label: str) -> None:
    """Merge keys into an existing JSON file without overwriting user values."""
    if path.is_file():
        try:
            existing = load_json_file(path)
        except Exception as exc:
            options.log(f"SKIP {label}: cannot parse {path} ({exc}); not overwriting")
            return
    else:
        existing = {}

    changed = False
    for key, value in updates.items():
        if key not in existing or options.force:
            existing[key] = value
            changed = True

    if not changed:
        options.log(f"OK   {label}: {path} (already configured)")
        return
    # Settings are merged key by key, so the file stays owned by the user.
    write_json(path, existing, options, label, owned=True)


def link_skill(source: Path, destination: Path, options: Options) -> None:
    """Symlink a skill directory into a VS Code skills location.

    An existing entry that is not the expected link is kept, unless `--force`
    is set. With `--force` a real folder goes to the backup folder; the
    installer never deletes user data.
    """
    if destination.is_symlink():
        try:
            current = destination.resolve()
        except OSError:
            current = None
        if current == source.resolve():
            options.log(f"OK   skill: {destination} -> {source}")
            return
        if not options.force and current is not None and current.exists():
            options.warn(f"skill {destination.name}: {destination} points elsewhere; kept (use --force)")
            return
        if options.dry_run:
            options.log(f"DRY  skill: would replace {destination}")
            return
        destination.unlink()
    elif destination.exists():
        if not options.force:
            options.warn(f"skill {destination.name}: {destination} is not a symlink; kept (use --force)")
            return
        if options.dry_run:
            options.log(f"DRY  skill: would back up and replace {destination}")
            return
        options.backup(destination)

    if options.dry_run:
        options.log(f"DRY  skill: would link {destination} -> {source}")
        return
    ensure_parent(destination)
    relative = os.path.relpath(source, destination.parent)
    destination.symlink_to(relative, target_is_directory=True)
    options.log(f"LINK skill: {destination} -> {relative}")


def install_skills(skills_root: Path, options: Options) -> None:
    """Symlink every valid skill into `skills_root`."""
    for skill_dir in skill_directories():
        link_skill(skill_dir, skills_root / skill_dir.name, options)


